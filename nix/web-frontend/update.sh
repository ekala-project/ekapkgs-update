#!/usr/bin/env bash
# Regenerate elm-srcs.nix and registry.dat from
# ekapkgs-update-web/frontend/elm.json. Run it after `elm install`.
#
# Hashes are computed here rather than with `elm2nix convert`, which reuses
# one hash for packages that share a version: nix-prefetch-url caches by
# name, and every tarball is named `<version>.tar.gz`. elm2nix is still
# used for the registry snapshot.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
elm_json="$root/ekapkgs-update-web/frontend/elm.json"
system="$(nix eval --impure --raw --expr builtins.currentSystem)"
tool() {
  echo "$(nix build --no-link --print-out-paths "$root#legacyPackages.$system.$1.${2:-out}")/bin/$1"
}
elm2nix="$(tool elm2nix)"
jq="$(tool jq bin)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

{
  echo '# Generated by `nix/web-frontend/update.sh` from'
  echo '# ekapkgs-update-web/frontend/elm.json. Do not edit by hand.'
  echo '{'
  # Test dependencies are pinned too: `elm make` verifies them for the
  # production build, and the test runner (nix/web-frontend-tests.nix)
  # compiles against them.
  "$jq" -r '.dependencies.direct + .dependencies.indirect
    + ."test-dependencies".direct + ."test-dependencies".indirect
    | to_entries[] | "\(.key) \(.value)"' "$elm_json" |
    while read -r name version; do
      hash="$(nix-prefetch-url --unpack --name "${name//\//-}-$version" \
        "https://github.com/$name/archive/$version.tar.gz" 2>/dev/null)"
      printf '  "%s" = {\n    version = "%s";\n    sha256 = "%s";\n  };\n' "$name" "$version" "$hash"
    done
  echo '}'
} >"$work/elm-srcs.nix"

cp "$elm_json" "$work/"
(cd "$work" && "$elm2nix" snapshot)

cp "$work/elm-srcs.nix" "$work/registry.dat" "$here/"
echo "Updated $here/elm-srcs.nix and $here/registry.dat"
